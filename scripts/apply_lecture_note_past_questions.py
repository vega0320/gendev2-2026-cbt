    payload = json.loads(DATA.read_text(encoding="utf-8"))
    questions = [q for q in payload["questions"] if q.get("sourceKind") not in {"historical-past", "lecture-practice"}]
    by_lecture = {}
    for q in questions:
        by_lecture.setdefault(q["lectureNumber"], q)
    for q in QUESTIONS:
        template = by_lecture[q["lectureNumber"]]
        q["lectureTitle"] = template["lectureTitle"]
        q["sourceLectureTitle"] = template["lectureTitle"]
        q["professor2026"] = template["professor2026"]
        q["professorAtExam"] = template["professor2026"]
    def lecture_order(value: str) -> tuple[int, str]:
        head = value.split("-", 1)[0]
        return (int(head) if head.isdigit() else 999, value)

    payload["questions"] = sorted(questions + QUESTIONS, key=lambda q: (*lecture_order(q["lectureNumber"]), -int(q["year"]), q["number"]))
    DATA.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"LECTURE_NOTE_PAST_APPLIED count={len(QUESTIONS)} total={len(payload['questions'])}")


