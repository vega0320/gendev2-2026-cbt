def main() -> None:
    payload = json.loads(DATA.read_text(encoding="utf-8"))
    questions = [q for q in payload["questions"] if q.get("lectureNumber") == "01"]
    if {q["id"] for q in questions} != set(MAP):
        raise SystemExit("lecture 01 mapping mismatch")
    for q in questions:
        concept, steps, review = PROFILES[MAP[q["id"]]]
        exp = q["explanation"]
        exp["conceptGroup"] = concept
        exp["reasoningSteps"] = steps
        exp["conceptReview"] = review
        # 과거 짧은 정규식 오인으로 keyJudgment가 오염된 두 문항을 직접 교정한다.
        answer = q["answers"][0]
        fact = exp["choiceExplanations"][answer - 1]
        exp["keyJudgment"] = fact
        q["explanationReviewStatus"] = "manual-reasoning-review-lecture01-2026-08-06"
    DATA.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"LECTURE01_REASONING_REVIEW_PASS questions={len(questions)}")


if __name__ == "__main__":
    main()
